def play1(freq, beats):
    duration = beat * beats
    start = time.monotonic()

    if freq == 0:
        cp.pixels.fill((0, 0, 0))
        while time.monotonic() - start < duration:
            pass
        return

    cp.start_tone(freq)

    i = random.randint(0, 9)
    cp.pixels[i] = random.choice(colors)

    light_off = False

    while time.monotonic() - start < duration:

        if not light_off and time.monotonic() - start >= 0.04:
            cp.pixels.fill((0, 0, 0))
            light_off = True

    cp.stop_tone()
    cp.pixels.fill((0, 0, 0))
    
